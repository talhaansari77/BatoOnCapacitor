import assert from "node:assert/strict";
import {programDepartment,programCounts,sessionsForProgram,appointmentsForProgram} from "../lib/carePrograms.js";
const hair={id:"hair",department:"hair_restoration",status:"active",total_sessions:6,sessions_used:3};
const skin={id:"skin",department:"skin_care",status:"completed",total_sessions:4,sessions_used:4};
const laser={id:"laser",department:"laser_hair_removal",status:"active",total_sessions:6,sessions_used:2};
const programs=[hair,skin,laser];
assert.equal(programDepartment({...hair,department:"skin_care",package_type:"full_head_hair_program"}),"skin_care");
assert.equal(programDepartment({package_type:"full_head_hair_program"}),"hair_restoration");
assert.equal(programDepartment({department:"multi_department",package_type:"full_head_hair_program"}),null);
assert.deepEqual(programCounts(hair),{used:3,total:6,remaining:3,progress:50});
assert.deepEqual(programCounts(skin),{used:4,total:4,remaining:0,progress:100});
assert.deepEqual(programCounts({total_sessions:0,sessions_used:2}),{used:2,total:0,remaining:0,progress:0});
assert.equal(programCounts({total_sessions:4,sessions_used:8}).progress,100);
assert.equal(programCounts({total_sessions:"bad",sessions_used:-2}).remaining,0);
const sessions=[{id:"a",package_id:"hair",department:"hair_restoration"},{id:"b",package_id:"skin",department:"skin_care"},{id:"c",department:"hair_restoration"},{id:"d",department:"laser_hair_removal"}];
assert.deepEqual(sessionsForProgram(sessions,hair,programs).map(x=>x.id),["a","c"]);
assert.deepEqual(sessionsForProgram(sessions,skin,programs).map(x=>x.id),["b"]);
assert.deepEqual(sessionsForProgram(sessions,hair,[...programs,{...hair,id:"old-hair",status:"completed"}]).map(x=>x.id),["a"]);
const appointments=[{id:"a",package_id:"hair"},{id:"b",department:"hair_restoration"},{id:"c",department:"laser_hair_removal"}];
assert.deepEqual(appointmentsForProgram(appointments,hair,programs).map(x=>x.id),["a","b"]);
assert.deepEqual(appointmentsForProgram(appointments,hair,[...programs,{...hair,id:"other-hair"}]).map(x=>x.id),["a"]);
assert.deepEqual(sessionsForProgram(sessions,null,programs),[]);
console.log("PASS: program department precedence, bounded counts, zero totals, separate program history and unambiguous legacy association.");
