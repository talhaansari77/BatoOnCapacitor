const {formatMoney,currencyTotals,productCurrency,convertMoney}=await import('../lib/commerce.js');
assert.equal(productCurrency({price:10},'kuwait'),null);
assert.equal(productCurrency({currency:'AED'},'kuwait'),'AED');
assert.equal(formatMoney('', 'AED'),'—');
assert.equal(convertMoney('bad','AED','AED',{}),null);
assert.equal(convertMoney(-1,'AED','AED',{}),null);
assert.equal(convertMoney(5,null,'AED',{}),null);
assert.equal(convertMoney(10,'AED','AED',{}),10);
assert.equal(convertMoney(10,'AED','KWD',{}),null);
