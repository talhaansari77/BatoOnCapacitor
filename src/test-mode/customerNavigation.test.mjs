assert.match(totals,/AED/);assert.match(totals,/KWD/);assert.match(totals,/Amount not recorded/);
console.log('PASS: recorded currencies remain fixed across branch changes, invalid prices are blocked, missing amounts are not treated as zero, and totals preserve separate currencies.');

