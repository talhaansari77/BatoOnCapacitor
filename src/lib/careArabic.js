const CARE_AR_CASE_INSENSITIVE = Object.fromEntries(Object.entries(CARE_AR).map(([key,value])=>[key.toLowerCase(),value]));

export function translateCareText(value) {
  if (typeof value !== "string") return value;
  const key = value.replace(/\s+/g, " ").trim();
  if (CARE_AR[key]) return CARE_AR[key];
  if (CARE_AR_CASE_INSENSITIVE[key.toLowerCase()]) return CARE_AR_CASE_INSENSITIVE[key.toLowerCase()];
  if (/^Session \d+$/.test(key)) return "الجلسة " + key.match(/\d+/)[0];
  if (/^\d+ photos? on file$/.test(key)) return "الصور المسجلة: " + key.match(/\d+/)[0];
  if (/^\d+ panels? on record$/.test(key)) return "التحاليل المسجلة: " + key.match(/\d+/)[0];
  if (/^\d+ drip programmes?$/.test(key)) return "برامج العلاج الوريدي: " + key.match(/\d+/)[0];
  return value;
}

const CARE_EN = Object.fromEntries(Object.entries(CARE_AR).map(([en,ar])=>[ar,en]));

// Legacy records may contain two complete translations separated by " / ".
// Select per line only when one side is English and the other is Arabic.
// Same-language slashes, medical acronyms, doses and ratios remain intact.
export function selectCareLanguage(value, language = "en") {
  if (typeof value !== "string") return value;
  const selected = value.split("\n").map(line => {
    const parts = line.split(" / ");
    if (parts.length !== 2) return line;
    const [a,b] = parts.map(part=>part.trim());
    const arabic = text => /[\u0600-\u06ff]/.test(text);
    const latin = text => /[A-Za-z]/.test(text);
    if (!arabic(a) && latin(a) && arabic(b)) return language === "ar" ? b : a;
    if (arabic(a) && !arabic(b) && latin(b)) return language === "ar" ? a : b;
    return line;
  }).join("\n");
  if (language === "ar") return selected.split("\n").map(translateCareText).join("\n");
  return selected.split("\n").map(line=>CARE_EN[line.replace(/\s+/g," ").trim()] || line).join("\n");
}

// Authored instructions must not fall back to the other language. Never invent
// a medical translation: keep the source record and show an explicit notice.
export function selectCareProse(value, language) {
  const selected = selectCareLanguage(value, language);
  if (typeof selected !== "string") return selected;
  const result = language === "ar" ? selected.replace(/\bBATO\b/g, "باتو") : selected;
  const ordinaryText = result.replace(/\b(?:PRP|PDRN|DNA|RNA|DHT|TSH|T3|T4|HbA1c|IGF-1|CoQ10|MPV|CRP|CBC|LDL|HDL|ALT|AST|B12|Q10|IV|IPL|Nd:YAG)\b/g, "").replace(/\b(?:test-[A-Za-z0-9-]+|[a-f0-9]{24})\b/g,"");
  const wrongLanguage = language === "ar"
    ? /[A-Za-z]/.test(ordinaryText)
    : /[\u0600-\u06ff]/.test(result);
  return wrongLanguage ? (language === "ar"
    ? "هذه الملاحظة غير متاحة بالعربية بعد. اطلب من فريق رعايتك نسخة بالعربية قبل الاعتماد عليها."
    : "This note is not available in English yet. Ask your care team for an English version before relying on it.") : result;
}
